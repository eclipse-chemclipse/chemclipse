package org.eclipse.chemclipse.msd.report.txt.preferences;

import org.eclipse.chemclipse.msd.report.txt.settings.StandaloneMassSpectrumReportSettings;
import org.eclipse.chemclipse.support.preferences.AbstractPreferenceSupplier;
import org.eclipse.chemclipse.support.preferences.IPreferenceSupplier;
import org.osgi.framework.FrameworkUtil;

public class PreferenceSupplier extends AbstractPreferenceSupplier {

	public static final String P_APPEND_FILES = "appendFiles";
	public static final boolean DEF_APPEND_FILES = false;

	public static IPreferenceSupplier INSTANCE() {

		return INSTANCE(PreferenceSupplier.class);
	}

	@Override
	public String getPreferenceNode() {

		return FrameworkUtil.getBundle(PreferenceSupplier.class).getSymbolicName();
	}

	@Override
	public void initializeDefaults() {

		putDefault(P_APPEND_FILES, Boolean.toString(DEF_APPEND_FILES));
	}

	public static StandaloneMassSpectrumReportSettings getMetadataReportSettings() {

		return new StandaloneMassSpectrumReportSettings();
	}
}
